export type Lang = 'en' | 'fr' | 'ar';

export const getTranslation = (key: string, lang: Lang): string => {
  const keys = key.split('.');
  let value: unknown = translations[lang];
  for (const k of keys) {
    if (value && typeof value === 'object' && k in (value as object)) {
      value = (value as Record<string, unknown>)[k];
    } else {
      return key;
    }
  }
  return typeof value === 'string' ? value : key;
};

/** Translate category name (stored in English in catalog) */
export const translateCategory = (category: string, lang: Lang): string => {
  return getTranslation(`categories.${category}`, lang) !== `categories.${category}`
    ? getTranslation(`categories.${category}`, lang)
    : category;
};

export const translateCategoryHint = (category: string, lang: Lang): string => {
  const key = `categoryHints.${category}`;
  const v = getTranslation(key, lang);
  return v !== key ? v : '';
};
